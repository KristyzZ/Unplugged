import Foundation

// Where a piece of station data came from, how old it is, and what it may be used for.
// SPEC.md: "Every status and price has a source, update timestamp, and data type:
// demo, observed, or predicted. Stale data is clearly marked."

/// What kind of data a status or price is. Only `demo` and `observed` values can be shown as
/// facts (demo only inside the labelled demo); a `predicted` value is an estimate.
enum DataClass: String, Codable, Hashable, CaseIterable {
    case demo       // generated by the prototype's simulation
    case observed   // reported by an operator / open-data feed, with a source and timestamp
    case predicted  // an estimate from history or a model
}

/// Freshness thresholds, in one place so they are easy to tune and test.
enum Freshness {
    /// A live connector status older than this is stale: we no longer know the connector's state.
    static let statusMaxAge: TimeInterval = 10 * 60
    /// Tariffs change rarely, so they stay trustworthy for longer.
    static let priceMaxAge: TimeInterval = 24 * 60 * 60
    /// A timestamp this far in the future means a wrong clock or bad data, not "very fresh".
    static let clockSkewTolerance: TimeInterval = 5 * 60
}

struct Provenance: Codable, Hashable {
    /// Human-readable origin, e.g. "Demo simulation" or "Via Lietuva OCPI".
    var source: String
    /// When the source reported the value.
    var timestamp: Date
    var dataClass: DataClass

    /// Data with no provenance at all. It is stale by construction, so unlabelled values are never
    /// treated as confirmed (this is the default for newly created connectors and stations).
    static let unspecified = Provenance(source: "Unspecified", timestamp: .distantPast, dataClass: .demo)

    static func demo(at date: Date, source: String = "Demo simulation") -> Provenance {
        Provenance(source: source, timestamp: date, dataClass: .demo)
    }

    /// Seconds since `timestamp` (never negative).
    func age(at now: Date) -> TimeInterval {
        max(0, now.timeIntervalSince(timestamp))
    }

    /// Stale when older than `maxAge`, or stamped implausibly far in the future.
    func isStale(at now: Date, maxAge: TimeInterval = Freshness.statusMaxAge) -> Bool {
        if timestamp.timeIntervalSince(now) > Freshness.clockSkewTolerance { return true }
        return age(at: now) > maxAge
    }
}

/// How much the app may do with a station (SPEC.md "Integration levels"). Each level includes the
/// ones before it; a lower level never offers session control or reservations.
enum IntegrationLevel: Int, Codable, Comparable, CaseIterable, Hashable {
    case discovery = 1      // location, connectors, power, operator; directions and operator hand-off
    case liveData           // plus live status and prices from a feed
    case accountPricing     // plus verified personal pricing for the user's plan
    case fullCharging       // plus starting/stopping sessions and payment inside Unplugged

    static func < (lhs: IntegrationLevel, rhs: IntegrationLevel) -> Bool { lhs.rawValue < rhs.rawValue }
}

struct StationCapabilities: Codable, Hashable {
    var level: IntegrationLevel
    /// True when the capabilities are made up for the demo. Real stations are never `simulated`.
    var simulated: Bool

    var providesLiveStatus: Bool { level >= .liveData }
    var supportsAccountPricing: Bool { level >= .accountPricing }
    var supportsSessionControl: Bool { level >= .fullCharging }

    /// Safe default for a station we know nothing else about: shown on the map, nothing more.
    static let discoveryOnly = StationCapabilities(level: .discovery, simulated: false)

    /// Capabilities of a demo station: explicitly simulated.
    static func demo(_ level: IntegrationLevel = .fullCharging) -> StationCapabilities {
        StationCapabilities(level: level, simulated: true)
    }
}
